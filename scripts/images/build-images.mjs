/**
 * Downloads the stock photos listed in scripts/images/images.json from Unsplash, crops them
 * to 3:2 and writes WebP files at each width to public/img/<key>-<width>.webp, then
 * regenerates src/app/core/constants/image-manifest.ts. The output is committed, so this only
 * needs to run when images.json changes:
 *
 *   npm run images                 # fetch anything missing
 *   npm run images -- --force      # re-fetch everything
 *   npm run images -- cat/temple   # (re)fetch selected keys
 *
 * Photos fall under the Unsplash licence: free for commercial use, no attribution required.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const list = JSON.parse(readFileSync(join(root, 'scripts/images/images.json'), 'utf8'));
const outDir = join(root, 'public/img');
const manifestPath = join(root, 'src/app/core/constants/image-manifest.ts');
const DEFAULT_WIDTHS = [480, 960, 1440];

const args = process.argv.slice(2);
const force = args.includes('--force');
const only = args.filter(a => !a.startsWith('--'));

const entries = Object.entries(list).filter(([key]) => !key.startsWith('_'));
const widthsOf = entry => entry.widths ?? DEFAULT_WIDTHS;
const fileOf = (key, w) => join(outDir, `${key}-${w}.webp`);

for (const [key, entry] of entries) {
  if (!entry.unsplash || (only.length && !only.includes(key))) continue;
  const widths = widthsOf(entry);
  if (!force && !only.length && widths.every(w => existsSync(fileOf(key, w)))) continue;
  try {
    const max = widths[widths.length - 1];
    const res = await fetch(`https://images.unsplash.com/photo-${entry.unsplash}?w=${Math.round(max * 1.25)}&fm=jpg&q=85`);
    if (!res.ok) throw new Error(`${res.status} downloading ${entry.unsplash}`);
    const buf = Buffer.from(await res.arrayBuffer());
    mkdirSync(dirname(fileOf(key, max)), { recursive: true });
    for (const w of widths) {
      await sharp(buf)
        .resize(w, Math.round((w * 2) / 3), { fit: 'cover', position: entry.position ?? sharp.strategy.attention })
        .webp({ quality: w > 1000 ? 70 : 74, effort: 6 })
        .toFile(fileOf(key, w));
    }
    console.log(`✓ ${key}`);
  } catch (err) {
    console.warn(`✗ ${key}: ${err.message}`);
    process.exitCode = 1;
  }
}

// List only images that exist on disk, so the app never points at a missing file.
const manifest = {};
for (const [key, entry] of entries) {
  const widths = widthsOf(entry);
  if (entry.unsplash && widths.every(w => existsSync(fileOf(key, w)))) manifest[key] = { widths, alt: entry.alt };
}
writeFileSync(
  manifestPath,
  `/* Generated by scripts/images/build-images.mjs. Do not edit by hand. */
export interface ImageEntry { widths: number[]; alt: string; }

export const IMAGES: Record<string, ImageEntry> = ${JSON.stringify(manifest, null, 2)};
`
);
console.log(`manifest: ${Object.keys(manifest).length} images`);
